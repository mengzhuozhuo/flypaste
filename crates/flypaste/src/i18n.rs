pub fn strings(language: Language) -> &'static Strings {
    match language {
        Language::Zh => &ZH,
        Language::En => &EN,
    }
}

pub fn from_settings() -> &'static Strings {
    let settings = fly_settings::Settings::load().unwrap_or_default();
    strings(settings.language)
}
